/**
 * Pure core domain types for `simple-budget-app`.
 *
 * Portability boundary (`project-plan/portability.md`):
 * Zero imports from `src/storage/`, browser DOM APIs, or Node globals.
 * All money values are represented as positive safe integers in minor units (`amountCents`).
 */

/** Recurring rules support income or expense (`deposit` is an Activity-only type). */
export type RuleType = "income" | "expense";

/** Recurring rule schedule (`monthly` in MVP; `dayOfMonth` in `1..31`). */
export interface Schedule {
  cadence: "monthly";
  dayOfMonth: number;
}

/** User-editable recurring income or expense rule. */
export interface RecurringRule {
  id: string;
  name: string;
  type: RuleType;
  amountCents: number;
  currency: string;
  schedule: Schedule;
  active: boolean;
  lastPostPeriod: string | null;
  createdAt: string;
  updatedAt: string;
  /** Reserved optional E2EE sync tombstone timestamp (ISO-8601 UTC; unused in MVP). */
  deletedAt?: string;
  /** Reserved optional originating device identifier for future E2EE sync conflict resolution. */
  deviceId?: string;
}

/** Input payload for creating a new `RecurringRule` (system-managed fields generated by API). */
export interface NewRule {
  name: string;
  type: RuleType;
  amountCents: number;
  currency?: string;
  schedule?: Schedule;
  active?: boolean;
}

/**
 * Partial update payload for user-editable `RecurringRule` fields.
 * Excludes system-managed fields (`id`, `currency`, `lastPostPeriod`, `createdAt`, `updatedAt`, `deletedAt`, `deviceId`).
 */
export interface RulePatch {
  name?: string;
  type?: RuleType;
  amountCents?: number;
  schedule?: Schedule;
  active?: boolean;
}

/** Activity record classification (`deposit` counts as money in, alongside `income`). */
export type ActivityType = "income" | "expense" | "deposit";

/** Provenance source of an `Activity` record. */
export type ActivitySource =
  | "manual"
  | "recurring"
  | "file-import"
  | "bank-sync";

/** Unified, always-editable transaction activity record (manual or recurring-generated). */
export interface Activity {
  id: string;
  type: ActivityType;
  amountCents: number;
  currency: string;
  dateTime: string;
  tags: string[];
  source: ActivitySource;
  /** Set when `source === "recurring"`; ID of the originating `RecurringRule`. */
  sourceRuleId?: string;
  /** Set when `source === "recurring"`; `"YYYY-MM"` period for which the activity was posted. */
  period?: string;
  /** Reserved for local CSV/OFX/QFX file import batch grouping. */
  importBatchId?: string;
  /** Reserved deduplication key (OFX/QFX FITID, CSV content hash, or bank-feed txn ID). */
  externalTxnId?: string;
  /** Reserved account identifier (file-import account label or future linked account). */
  sourceAccountId?: string;
  /** Optional free-text note. */
  memo?: string;
  createdAt: string;
  updatedAt: string;
  /** Reserved optional E2EE sync tombstone timestamp (ISO-8601 UTC; unused in MVP). */
  deletedAt?: string;
  /** Reserved optional originating device identifier for future E2EE sync conflict resolution. */
  deviceId?: string;
}

/** Input payload for creating a new manual `Activity` (system-managed fields generated by API). */
export interface NewActivity {
  type: ActivityType;
  amountCents: number;
  currency?: string;
  dateTime?: string;
  tags?: string[];
  memo?: string;
}

/**
 * Partial update payload for user-editable `Activity` fields.
 * Excludes provenance, dedupe keys, audit timestamps, and sync tombstones.
 */
export interface ActivityPatch {
  type?: ActivityType;
  amountCents?: number;
  dateTime?: string;
  tags?: string[];
  memo?: string;
}

/** Versioned local JSON backup envelope (`schemaVersion: 1`). */
export interface BudgetBackup {
  schemaVersion: 1;
  exportedAt: string;
  rules: RecurringRule[];
  activities: Activity[];
}

/**
 * Post-MVP (Phase 6 store-release gate) passphrase-encrypted backup envelope
 * wrapping UTF-8 `BudgetBackup` JSON via WebCrypto (`PBKDF2-HMAC-SHA256` + `AES-256-GCM`).
 */
export interface EncryptedBudgetBackup {
  schemaVersion: 1;
  enc: {
    alg: "AES-256-GCM";
    kdf: "PBKDF2-HMAC-SHA256";
    iter: number;
    salt: string;
    iv: string;
  };
  ciphertext: string;
}

/** Intersecting filter predicates for querying/searching activities. */
export interface ActivitySearchFilter {
  /** ISO-8601 UTC lower bound, inclusive (e.g. `"2026-01-01T00:00:00Z"`). */
  since?: string;
  /** ISO-8601 UTC upper bound, exclusive (e.g. `"2026-12-01T00:00:00Z"`). */
  until?: string;
  /** Activity's `tags` array must include this tag. */
  tag?: string;
  /** Activity's `type` must equal this type. */
  type?: ActivityType;
}

/** Alias of `ActivitySearchFilter` used by `BudgetApi.listActivities(filter?)`. */
export type ActivityFilter = ActivitySearchFilter;

/** Per-tag money-in / money-out rollup in integer cents. */
export interface TagSummary {
  tag: string;
  totalInCents: number;
  totalOutCents: number;
}
